"""Count images and boxes per class, per split and per source, from the label files.

    python -m dashcam_ml.stats --dataset data/processed/merged --out results/dataset_stats

Writes <out>.json and <out>.md. These are the only dataset numbers we quote; nothing
is typed in by hand.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path

from dashcam_ml.classes import DEFAULT_CLASSES, load_classes
from dashcam_ml.yolo_io import read_yolo_labels


def source_of(name: str) -> str:
    """Images are named '<source>__...' by the converters."""
    return name.split("__", 1)[0] if "__" in name else "unknown"


def compute_stats(dataset: Path, class_names: list[str]) -> dict:
    splits: dict[str, dict] = {}
    for split_dir in sorted(p for p in (dataset / "labels").iterdir() if p.is_dir()):
        boxes: Counter[str] = Counter()
        images_with: Counter[str] = Counter()
        per_source: dict[str, Counter[str]] = defaultdict(Counter)
        n_images = n_background = 0
        for lbl in sorted(split_dir.glob("*.txt")):
            n_images += 1
            src = source_of(lbl.stem)
            per_source[src]["images"] += 1
            classes_here = set()
            rows = read_yolo_labels(lbl)
            for cls, _ in rows:
                name = class_names[cls]
                boxes[name] += 1
                per_source[src][name] += 1
                classes_here.add(name)
            images_with.update(classes_here)
            n_background += not rows
        splits[split_dir.name] = {
            "images": n_images,
            "background_images": n_background,
            "boxes_per_class": {c: boxes.get(c, 0) for c in class_names},
            "images_per_class": {c: images_with.get(c, 0) for c in class_names},
            "per_source": {s: dict(c) for s, c in sorted(per_source.items())},
        }
    return {
        "dataset": str(dataset),
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "classes": class_names,
        "splits": splits,
    }


def to_markdown(stats: dict, extra_sections: str = "") -> str:
    names: list[str] = stats["classes"]
    splits = list(stats["splits"])
    lines = [
        "# Dataset statistics",
        "",
        f"_Generated by `python -m dashcam_ml.stats` at {stats['generated_at']}. Do not edit by hand._",
        "",
        "| split | images | background images | boxes |",
        "|---|---:|---:|---:|",
    ]
    for s in splits:
        d = stats["splits"][s]
        lines.append(f"| {s} | {d['images']} | {d['background_images']} | {sum(d['boxes_per_class'].values())} |")
    lines += ["", "## Boxes per class (images containing the class in brackets)", "",
              "| class | " + " | ".join(splits) + " |", "|---|" + "---:|" * len(splits)]
    for c in names:
        cells = [f"{stats['splits'][s]['boxes_per_class'][c]} ({stats['splits'][s]['images_per_class'][c]})"
                 for s in splits]
        lines.append(f"| {c} | " + " | ".join(cells) + " |")
    lines += ["", "## Images per source", "", "| source | " + " | ".join(splits) + " |",
              "|---|" + "---:|" * len(splits)]
    sources = sorted({src for s in splits for src in stats["splits"][s]["per_source"]})
    for src in sources:
        cells = [str(stats["splits"][s]["per_source"].get(src, {}).get("images", 0)) for s in splits]
        lines.append(f"| {src} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n" + extra_sections


def write_stats(stats: dict, out: Path, extra_md: str = "") -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(stats, indent=2), encoding="utf-8")
    out.with_suffix(".md").write_text(to_markdown(stats, extra_md), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dataset", type=Path, default=Path("data/processed/merged"))
    p.add_argument("--classes", type=Path, default=DEFAULT_CLASSES)
    p.add_argument("--out", type=Path, default=Path("results/dataset_stats"))
    a = p.parse_args(argv)
    stats = compute_stats(a.dataset, load_classes(a.classes))
    write_stats(stats, a.out)
    print(to_markdown(stats))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
