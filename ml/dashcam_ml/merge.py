"""Merge converted IDD + obstacle pools into one YOLO dataset and write its stats.

    python -m dashcam_ml.merge --idd data/processed/idd --obstacles data/processed/obstacles \
        --out data/processed/merged

- IDD keeps its official train/val split.
- Obstacle pools are split by photo group with a seeded hash, so (a) augmented copies of
  one photo never straddle train and val, and (b) adding a new dataset later does not
  reshuffle the images that were already assigned.
- Exact duplicate images across obstacle datasets (same bytes) are kept once; the same
  photo is often re-uploaded to several Roboflow projects.
- Writes <out>/data.yaml (no `path:` key; our train/evaluate scripts pass its absolute
  location, so the folder can be moved or uploaded to Kaggle as-is) and
  results/dataset_stats.{json,md}.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import yaml

from dashcam_ml.classes import DEFAULT_CLASSES, load_classes
from dashcam_ml.stats import compute_stats, write_stats
from dashcam_ml.yolo_io import IMAGE_SUFFIXES, place_image


def assign_split(group: str, val_frac: float, seed: int) -> str:
    """Deterministic: the same group always lands in the same split for a given seed."""
    h = int.from_bytes(hashlib.sha1(f"{seed}:{group}".encode()).digest()[:8], "big")
    return "val" if h / 2**64 < val_frac else "train"


def file_digest(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()


def _images_by_stem(img_dir: Path) -> dict[str, Path]:
    return {p.stem: p for p in img_dir.iterdir() if p.suffix.lower() in IMAGE_SUFFIXES}


def merge(
    idd: Path | None,
    obstacles: Path | None,
    out: Path,
    class_names: list[str],
    val_frac: float = 0.15,
    seed: int = 0,
    mode: str = "hardlink",
) -> dict:
    if out.exists():
        shutil.rmtree(out)  # rebuilt from scratch every time so stale images never linger
    summary: dict = {"val_frac": val_frac, "seed": seed, "sources": {}, "duplicates_removed": 0}

    def put(img: Path, lbl: Path, split: str) -> None:
        place_image(img, out / "images" / split / img.name, None, mode)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
        shutil.copyfile(lbl, out / "labels" / split / lbl.name)

    if idd:
        for split in ("train", "val"):
            imgs = _images_by_stem(idd / "images" / split)
            for stem, img in sorted(imgs.items()):
                put(img, idd / "labels" / split / f"{stem}.txt", split)
            summary["sources"].setdefault("idd", {})[split] = len(imgs)

    if obstacles:
        seen: dict[str, str] = {}
        for ds_dir in sorted(p for p in obstacles.iterdir() if (p / "manifest.json").exists()):
            manifest = json.loads((ds_dir / "manifest.json").read_text(encoding="utf-8"))
            imgs = _images_by_stem(ds_dir / "images")
            counts = {"train": 0, "val": 0, "duplicates": 0}
            for item in manifest["images"]:
                img = imgs[item["name"]]
                digest = file_digest(img)
                if digest in seen:
                    counts["duplicates"] += 1
                    continue
                seen[digest] = item["name"]
                split = assign_split(item["group"], val_frac, seed)
                put(img, ds_dir / "labels" / f"{item['name']}.txt", split)
                counts[split] += 1
            summary["sources"][ds_dir.name] = {**counts, "license": manifest["report"].get("license"),
                                               "url": manifest["report"].get("source")}
            summary["duplicates_removed"] += counts["duplicates"]

    for split in ("train", "val"):
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
    data_yaml = {"train": "images/train", "val": "images/val", "names": dict(enumerate(class_names))}
    (out / "data.yaml").write_text(
        "# Generated by dashcam_ml.merge. Pass this file's absolute path to Ultralytics.\n"
        + yaml.safe_dump(data_yaml, sort_keys=False), encoding="utf-8")
    (out / "merge_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def sources_markdown(summary: dict) -> str:
    lines = ["", "## Sources and licences", "",
             f"Obstacle datasets split by photo group: val fraction {summary['val_frac']}, seed {summary['seed']}. "
             f"Exact duplicate images removed: {summary['duplicates_removed']}.", "",
             "| source | train | val | licence | url |", "|---|---:|---:|---|---|"]
    for name, s in summary["sources"].items():
        lic = "IDD terms (research, non-commercial)" if name == "idd" else (s.get("license") or "UNKNOWN")
        lines.append(f"| {name} | {s.get('train', 0)} | {s.get('val', 0)} | {lic} | {s.get('url') or ''} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--idd", type=Path, default=None, help="output of convert.idd")
    p.add_argument("--obstacles", type=Path, default=None, help="folder of convert.roboflow pools")
    p.add_argument("--out", type=Path, default=Path("data/processed/merged"))
    p.add_argument("--classes", type=Path, default=DEFAULT_CLASSES)
    p.add_argument("--val-frac", type=float, default=0.15)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--mode", choices=["hardlink", "copy", "symlink"], default="hardlink")
    p.add_argument("--stats-out", type=Path, default=Path("results/dataset_stats"))
    a = p.parse_args(argv)
    if not a.idd and not a.obstacles:
        p.error("give --idd and/or --obstacles")
    names = load_classes(a.classes)
    summary = merge(a.idd, a.obstacles, a.out, names, a.val_frac, a.seed, a.mode)
    stats = compute_stats(a.out, names)
    stats["merge"] = summary
    write_stats(stats, a.stats_out, sources_markdown(summary))
    print(f"merged dataset: {a.out / 'data.yaml'}")
    print(f"stats: {a.stats_out.with_suffix('.md')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
